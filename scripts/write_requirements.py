"""Write app/requirements.txt for Posit Connect Cloud, which installs from that file.

Every dependency comes pinned from uv.lock. pi-briefing is not on PyPI, so it comes from direct
wheel URLs, one per Linux architecture, chosen by environment markers:

    uv run --no-project python scripts/write_requirements.py \\
        --wheel-base-url https://github.com/OWNER/REPO/releases/download/v0.1.0
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "app" / "requirements.txt"
LINUX_WHEELS = {
    "x86_64": "manylinux_2_17_x86_64",
    "aarch64": "manylinux_2_17_aarch64",
}


def locked_requirements() -> str:
    """Third-party pins from uv.lock, without the project and without pi-briefing."""
    command = [
        "uv", "export", "--format", "requirements-txt", "--no-hashes", "--no-dev",
        "--no-emit-project", "--no-emit-package", "pi-briefing", "--no-header", "--frozen",
    ]  # fmt: skip
    return subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def wheel_lines(base_url: str) -> list[str]:
    version = json.loads((ROOT / "agent" / "package.json").read_text())["version"]
    lines = []
    for machine, tag in LINUX_WHEELS.items():
        url = f"{base_url.rstrip('/')}/pi_briefing-{version}-py3-none-{tag}.whl"
        marker = f'sys_platform == "linux" and platform_machine == "{machine}"'
        lines.append(f"pi-briefing @ {url} ; {marker}")
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--wheel-base-url", required=True, help="where the Linux wheels are served")
    args = parser.parse_args()
    header = "# Generated by scripts/write_requirements.py from uv.lock; do not edit.\n"
    OUTPUT.write_text(
        header + "\n".join(wheel_lines(args.wheel_base_url)) + "\n" + locked_requirements()
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
